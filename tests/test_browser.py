import os
from threading import Thread

import pytest
from playwright.sync_api import expect, sync_playwright
from werkzeug.serving import make_server

from app.db import value
from app.demo import seed
from app.settings import change


@pytest.mark.parametrize("width,height", [(390, 844), (820, 1180), (1440, 900)])
def test_daily_workflow(app, engine, width, height):
    with engine.begin() as c:
        seed(c)
        change(c, {"action": "new_bank", "name": "Second Bank"})
    server = make_server("127.0.0.1", 0, app, threaded=True)
    base = f"http://127.0.0.1:{server.server_port}"
    thread = Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        with sync_playwright() as p:
            b = p.chromium.launch(
                executable_path=os.getenv("CHROMIUM_PATH"), args=["--no-zygote", "--use-angle=swiftshader"]
            )
            page = b.new_page(viewport={"width": width, "height": height})
            page.set_default_timeout(5000)
            errors = []
            page.on("pageerror", lambda err: errors.append(str(err)))
            page.goto(base + "/")
            page.get_by_label("Username").fill("tester")
            page.get_by_label("Password").fill("test-password-1234")
            page.get_by_role("button", name="Sign in").click()
            expect(page.get_by_role("heading", name="Overview")).to_be_visible()

            def visit(module):
                page.goto(base + "/workspace/" + module)
                assert page.evaluate("document.documentElement.scrollWidth<=innerWidth"), module

            def open_form(kind):
                f = page.locator('form[data-kind="' + kind + '"]').first
                if not f.is_visible():
                    dialog_id = f.locator("..").get_attribute("id")
                    page.locator(f'button[data-dialog="{dialog_id}"]').click()
                return f

            def save(f):
                with page.expect_navigation():
                    f.get_by_role("button", name="Save", exact=True).click()
                expect(page.locator("[role=status]")).to_contain_text("Saved record")

            expect(page.get_by_role("heading", name="Sales and expenses", exact=True)).to_be_visible()
            canvas = page.locator(".chart-stage canvas")
            canvas.hover(position={"x": 65, "y": 60})
            expect(page.locator(".chart-tooltip")).to_contain_text("Sales NPR")
            page.locator("select[name=chart_type]").select_option("line")
            page.locator("select[name=chart_days]").select_option("30")
            page.get_by_role("button", name="Apply chart filters").click()
            expect(page.locator("[data-chart]")).to_have_attribute("data-chart-type", "line")
            page.get_by_text("Chart data", exact=True).click()
            chart_data = page.locator(".chart-data")
            expect(chart_data.locator("tbody tr:visible")).to_have_count(20)
            chart_data.get_by_role("button", name="Next").click()
            expect(chart_data.locator("tbody tr:visible")).to_have_count(10)
            page.locator("select[name=chart_type]").select_option("donut")
            page.locator("select[name=chart_series]").select_option("sales")
            page.locator("select[name=chart_counter]").select_option("1")
            page.get_by_role("button", name="Apply chart filters").click()
            expect(page.locator("[data-chart]")).to_have_attribute("data-chart-type", "donut")
            expect(page.locator(".chart-legend")).to_have_text("Sales")
            canvas.focus()
            canvas.press("ArrowRight")
            expect(page.locator(".chart-tooltip")).to_contain_text("NPR 3,500.00")
            page.get_by_role("link", name="New expense", exact=False).click()
            expect(page.get_by_role("dialog", name="Record new bill", exact=False)).to_be_visible()
            f = open_form("bill")
            f.get_by_label("Item name").click()
            picker = page.get_by_role("dialog", name="Choose an item")
            picker.get_by_label("Category").select_option("Food")
            picker.get_by_role("searchbox").fill("unmatched")
            expect(picker.get_by_text("No matching catalogue items.")).to_be_visible()
            picker.get_by_role("searchbox").fill("pork kg")
            expect(picker.get_by_role("button", name="Momo", exact=False)).not_to_be_visible()
            picker.get_by_role("button", name="Pork", exact=False).click()
            f.locator("[name=row_amount]").fill("700")
            expect(f.locator("[name=row_category]")).to_have_value("Food")
            expect(f.locator("[name=row_unit]")).to_have_value("kg")
            f.locator("[name=row_qty]").fill("1")
            f.get_by_role("button", name="Add item", exact=False).click()
            f.get_by_label("Item name").nth(1).click()
            picker.get_by_role("button", name="Enter an item manually").click()
            f.locator("[name=row_name]").nth(1).fill("Napkins")
            f.locator("[name=row_category]").nth(1).fill("Supplies")
            f.locator("[name=row_amount]").nth(1).fill("100")
            f.locator("[name=party]").fill("Meat Co")
            f.locator("[name=payment_mode]").select_option("split")
            f.locator("[name=cash]").fill("300")
            save(f)
            main = page.locator("section.card").filter(
                has=page.get_by_role("heading", name="Main Counter", exact=True)
            )
            main.get_by_role("link", name="View expenses").click()
            expect(page.get_by_role("heading", name="Expense history")).to_be_visible()
            expect(page.get_by_role("navigation", name="Breadcrumb")).to_contain_text("Counters")
            expect(page.get_by_role("cell", name="Meat Co", exact=True)).to_be_visible()
            visit("counters")
            sub = page.locator("section.card").filter(
                has=page.get_by_role("heading", name="Counter 2", exact=True)
            )
            sub.get_by_role("button", name="Expense", exact=True).click()
            bill = page.locator("form[data-kind=bill]")
            expect(bill.locator("[name=counter_id]")).to_have_value("2")
            bill.get_by_role("button", name="Cancel").click()
            sub.get_by_role("button", name="Income", exact=True).click()
            f = open_form("sale")
            expect(f.locator("[name=counter_id]")).to_have_value("2")
            f.locator("[name=cash]").fill("600")
            for index, (bank, amount) in enumerate([("Demo Bank", "150"), ("Second Bank", "250")]):
                f.get_by_role("button", name="Add bank").click()
                f.get_by_label("Bank account").nth(index).select_option(label=bank)
                f.get_by_label("Bank amount").nth(index).fill(amount)
            for index, (customer, amount) in enumerate([("Asha", "100"), ("Ram", "100")]):
                f.get_by_role("button", name="Add customer").click()
                f.get_by_label("Customer", exact=True).nth(index).fill(customer)
                f.get_by_label("Credit amount").nth(index).fill(amount)
            expect(f.locator("output")).to_have_text("Total sales · NPR 1200.00")
            f.get_by_label("Item name").click()
            picker.get_by_role("searchbox").fill("momo")
            picker.get_by_role("button", name="Momo", exact=False).click()
            expect(f.locator("[name=row_name]")).to_have_value("Momo")
            f.locator("[name=row_qty]").fill("4")
            f.get_by_role("button", name="Add item", exact=False).click()
            expect(f.locator("[name=row_name]")).to_have_count(2)
            f.get_by_role("button", name="Remove row", exact=True).nth(1).click()
            save(f)
            visit("credits")
            for action in ("Record payment", "Record collection"):
                if action == "Record collection":
                    page.get_by_role("link", name="Customer receivables", exact=True).click()
                page.get_by_role("button", name=action).first.click()
                modal = page.locator("#settle")
                modal.locator("[name=account_id]").select_option(label="Main Counter cash")
                modal.locator("[name=amount]").fill("50")
                save(modal)
            page.get_by_role("link", name="Asha", exact=True).click()
            expect(page.get_by_role("heading", name="Asha · Receivable history")).to_be_visible()
            expect(page.get_by_role("cell", name="Credit sale", exact=True)).to_be_visible()
            expect(page.get_by_role("cell", name="Collection", exact=True)).to_be_visible()
            expect(page.get_by_role("cell", name="-50.00", exact=True)).to_be_visible()
            assert page.evaluate("document.documentElement.scrollWidth<=innerWidth")
            visit("stock")
            f = open_form("stock_count")
            expect(page.get_by_role("heading", name="Inventory at a glance")).to_be_visible()
            f.get_by_role("button", name="Browse items").click()
            expect(picker.get_by_role("button", name="Momo", exact=False)).to_have_count(0)
            picker.get_by_role("searchbox").fill("pork")
            picker.get_by_role("button", name="Pork", exact=False).click()
            expect(f.locator("[name=name]")).to_have_value("Pork")
            expect(f.locator("output")).to_have_text("Base unit · kg")
            f.locator("[name=actual]").fill("8")
            save(f)
            visit("money")
            expect(page.get_by_role("button", name="Set opening bank balance")).to_be_visible()
            expect(page.get_by_role("heading", name="Cash and Banking", exact=True)).to_be_visible()
            expect(page.get_by_role("heading", name="Cash drawers")).to_be_visible()
            expect(page.get_by_role("heading", name="Bank accounts")).to_be_visible()
            expect(page.get_by_role("heading", name="Cash and bank transactions")).to_be_visible()
            page.get_by_label("Period").select_option("all")
            expect(page.get_by_text("All dates through", exact=False)).to_be_visible()
            expect(page.get_by_role("cell", name="Opening", exact=True)).to_be_visible()
            page.get_by_label("Account", exact=True).select_option(label="Second Bank")
            page.get_by_role("button", name="Apply", exact=True).click()
            expect(page.get_by_role("cell", name="Second Bank", exact=True)).to_be_visible()
            expect(page.get_by_role("cell", name="Main Counter cash", exact=True)).to_have_count(0)
            visit("counters")
            expect(page.get_by_role("heading", name="Cash transactions")).to_be_visible()
            for title, party in [("Receivables collected", "Asha"), ("Payables paid", "Meat Co")]:
                detail = page.locator("details").filter(has_text=title + " · NPR 50.00")
                detail.locator("summary").click()
                expect(detail.get_by_role("cell", name=party, exact=True)).to_be_visible()
                expect(detail.get_by_role("link")).to_have_attribute(
                    "href", "/record/" + detail.get_by_role("link").inner_text().lstrip("#")
                )
            f = open_form("transfer")
            f.locator("[name=account_id]").select_option(label="Main Counter cash")
            f.locator("[name=to_id]").select_option(label="Counter 2 cash")
            f.locator("[name=amount]").fill("1000")
            save(f)
            visit("counters")
            page.locator(".tabs").get_by_role("link", name="Counter 2").click()
            expect(page.get_by_role("heading", name="Main Counter", exact=True)).to_have_count(0)
            page.get_by_label("Direction").select_option("out")
            page.get_by_role("button", name="Apply", exact=True).click()
            expect(page.get_by_text("No matching records.")).to_be_visible()
            page.get_by_label("Direction").select_option("in")
            page.get_by_role("button", name="Apply", exact=True).click()
            expect(page.get_by_role("cell", name="Transfer", exact=True)).to_be_visible()
            visit("counters")
            f = open_form("handover")
            f.locator("[name=counter_id]").select_option("2")
            expect(f.locator("[name=counter_id] option", has_text="Main Counter")).to_be_disabled()
            f.locator("[name=actual]").fill("1590")
            expect(f.locator("output")).to_contain_text("Variance · NPR -10.00")
            expect(f.get_by_label("Variance notes")).to_have_attribute("required", "")
            f.get_by_label("Variance notes").fill("Drawer shortage")
            save(f)
            f = open_form("handover")
            f.locator("[name=actual]").fill("21790")
            save(f)
            f = open_form("close")
            with page.expect_navigation():
                f.get_by_role("button", name="Confirm closing").click()
            expect(page.locator("[role=status]")).to_be_visible()
            visit("reports")
            page.locator("select[name=report]").select_option("closing")
            page.locator("table a").first.click()
            expect(page.get_by_role("heading", name="Close ·", exact=False)).to_be_visible()
            visit("settings")
            headings = page.get_by_role("heading", level=2).all_text_contents()
            assert headings.index("Product catalogue") > headings.index("Physical stock counts")
            page.get_by_role("button", name="Add product").click()
            product = page.get_by_role("dialog", name="Add product")
            product.get_by_label("Product name").fill("Iced tea")
            product.get_by_label("Category").fill("Beverage")
            product.get_by_label("Base unit").fill("l")
            save(product)
            expect(page.get_by_role("cell", name="Iced tea", exact=True)).to_be_visible()
            page.get_by_role("button", name="Add product").click()
            product.get_by_label("Product name").fill(" ICED TEA ")
            product.get_by_label("Category").fill("Beverage")
            product.get_by_label("Base unit").fill("l")
            product.get_by_role("button", name="Save", exact=True).click()
            expect(product.get_by_role("alert")).to_contain_text("already exists")
            product.press("Escape")
            expect(product).not_to_be_visible()
            if width == 1440:
                page.get_by_role("button", name="Add product").click()
                product.get_by_label("Product name").fill("House juice")
                product.get_by_label("Category").fill("Beverage")
                product.get_by_role("button", name="Add variation").click()
                product.get_by_role("button", name="Add variation").click()
                product.get_by_role("button", name="Remove variation").nth(1).click()
                for i, (variant, unit) in enumerate([("Glass", "ml"), ("Pitcher", "l")]):
                    product.get_by_label("Variation (optional)").nth(i).fill(variant)
                    product.get_by_label("Base unit").nth(i).fill(unit)
                product.get_by_label("Track stock").nth(1).select_option("on")
                save(product)
                expect(page.get_by_role("cell", name="House juice · Glass", exact=True)).to_be_visible()
                expect(page.get_by_role("cell", name="House juice · Pitcher", exact=True)).to_be_visible()
                page.get_by_label("Appearance").select_option("dark")
                expect(page.locator("html")).to_have_attribute("data-theme", "dark")
                page.reload()
                expect(page.locator("html")).to_have_attribute("data-theme", "dark")
                item = page.get_by_role("row").filter(has_text="Iced tea")
                item.get_by_role("button", name="Edit", exact=True).click()
                edit = item.get_by_role("dialog", name="Edit", exact=True)
                edit.get_by_label("Variation (optional)").fill("Glass")
                edit.get_by_label("Base unit").fill("ml")
                edit.get_by_text("Learn more").click()
                expect(edit.get_by_text("Base unit and stock tracking", exact=False)).to_be_visible()
                save(edit)
                variant = page.get_by_role("row").filter(has_text="Iced tea · Glass")
                variant.get_by_role("button", name="Archive", exact=True).click()
                save(variant.get_by_role("dialog", name="Archive", exact=True))
                expect(variant.get_by_role("button", name="Restore", exact=True)).to_be_visible()
                bank = page.get_by_role("listitem").filter(has_text="Second Bank")
                bank.get_by_role("button", name="Edit", exact=True).click()
                edit_bank = bank.get_by_role("dialog", name="Edit", exact=True)
                edit_bank.get_by_label("Account name").fill("Second Bank Savings")
                save(edit_bank)
                expect(
                    page.locator(".settings-list li > span").get_by_text("Second Bank Savings", exact=True)
                ).to_be_visible()
                page.get_by_role("button", name="Activity").click()
                expect(page.get_by_role("dialog", name="Recent activity")).to_contain_text("Settings change")
                page.keyboard.press("Escape")
            if width == 390:
                page.get_by_role("button", name="More", exact=True).click()
                page.locator("#modules").get_by_role("link", name="Search all records").click()
                page.get_by_role("searchbox").fill("Napkins")
                page.get_by_role("button", name="Search", exact=True).click()
                expect(page.get_by_role("heading", name="Matching records")).to_be_visible()
                expect(page.get_by_role("link", name="Napkins", exact=True)).to_be_visible()
                page.evaluate("navigator.serviceWorker.ready")
                page.reload()
                keys = page.evaluate(
                    "async()=>{const c=await caches.open('rms-ledger-shell-v6');return (await c.keys()).map(r=>new URL(r.url).pathname)}"
                )
                assert keys and all(path.startswith("/static/") for path in keys)
                page.get_by_role("button", name="More", exact=True).click()
                page.locator("#modules").get_by_role("button", name="Sign out").click()
                expect(page.get_by_role("heading", name="Sign in to RMS")).to_be_visible()
                page.goto(base + "/workspace/credits")
                expect(page.get_by_role("heading", name="Sign in to RMS")).to_be_visible()
            assert errors == []
            with engine.begin() as c:
                assert value(c, "select count(*) from closing_snapshot") == 1
                assert value(c, "select count(*) from item where name like 'Iced tea%'") == 1
                assert value(c, "select count(*) from event where kind='configuration'") == (
                    5 if width == 1440 else 1
                )
            b.close()
    finally:
        server.shutdown()
        thread.join()
